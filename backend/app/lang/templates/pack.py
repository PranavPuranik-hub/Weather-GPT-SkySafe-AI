def get_localized_action(action_id: str, fact_slots: Dict[str, Any], lang: str = "en") -> Optional[str]:
    """
    Retrieve and format the localized action template.
    Renders numbers in target language digits.
    Falls back to English if target language template is missing.
    """
    templates = ACTION_TEMPLATES.get(action_id)
    if not templates:
        return None

    tmpl = templates.get(lang.lower()) or templates.get("en")
    if not tmpl:
        return None

    # Prepare slots with rendered native digits
    rendered_slots = {}
    for k, v in fact_slots.items():
        rendered_slots[k] = render_fact_slot(v, lang)

    try:
        return tmpl.format(**rendered_slots)
    except KeyError:
        # If any slot is missing, use empty string for it
        return tmpl
